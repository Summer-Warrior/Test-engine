  private val byId: Map<String, TrainerArchetype> by lazy { allTrainerTypes.associateBy { it.id } }

  fun findById(id: String): TrainerArchetype? = byId[id]

  fun filterByCategory(category: TrainerCategory?): List<TrainerArchetype> =
    if (category == null) allTrainerTypes else allTrainerTypes.filter { it.category == category }

  /**
   * Resolves a signature enemy Dex ID for the given Trainer Type within the active region,
   * seamlessly drawing from both the trainer's signature species and the region's complete
   * multi-source Pokédex habitat so all #0001-#1025 Pokémon appear naturally.
   */
  fun resolveEnemyDexForTrainer(
    archetype: TrainerArchetype,
    regionId: String,
    seedNonce: Int = 0,
  ): Int {
    val regionPool = NationalAtlasIndex.dexPoolForRegion(regionId)
    val preferredTypeNames = archetype.preferredTypes.map { it.displayName.lowercase() }.toSet()
    val matchingRegional = regionPool.filter { dex ->
      val item = NationalAtlasIndex.peekSpecies(dex)
      item.primaryType.lowercase() in preferredTypeNames || item.secondaryType.lowercase() in preferredTypeNames
    }
    val combined = (archetype.signatureDexIds + matchingRegional.take(20)).distinct().ifEmpty {
      listOf(25, 6, 94, 448, 658, 384)
    }
    return combined[abs(seedNonce) % combined.size]
  }
